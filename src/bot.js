// ตัวจำแนกคำถามที่กลุ่มสร้างเอง: n-gram ตัวอักษร + TF-IDF + เทียบความคล้าย (cosine) กับประโยคที่ใช้สอน
function botNorm(s) {
  return String(s || '').toLowerCase()
    .replace(/tm\d{4}-\d{2}/g, ' ')
    .replace(/พอยต์|พอยท์|พ้อย/g, 'point').replace(/แต้ม/g, 'point')
    .replace(/ไหม|มั้ย|มั๊ย|ป่าว|ปะ|รึเปล่า|หรือเปล่า/g, 'ไหม')
    .replace(/เท่าไหร่|เท่าไร|เท่าใด/g, 'เท่าไร')
    .replace(/(ครับ|ค่ะ|คะ|ค่า|คับ|ฮะ|จ้ะ|จ้า|จ๊ะ|นะ|หน่อย|อ่ะ|อะ|ด้วย)+(?=[\s?!.,]|$)/g, '') // คำลงท้าย (เฉพาะท้ายประโยค/ท้ายวลี)
    .replace(/[^฀-๿a-z0-9]/g, '');
}
function botGrams(s) {
  var t = '^' + botNorm(s) + '$', g = {};
  for (var n = 2; n <= 3; n++) for (var i = 0; i + n <= t.length; i++) { var k = t.substr(i, n); g[k] = (g[k] || 0) + 1; }
  return g;
}
function botTrain(examples) { // examples: [[text, intent]]
  var docs = examples.map(function (e) { return { g: botGrams(e[0]), intent: e[1], text: e[0] }; }).filter(function (d) { return Object.keys(d.g).length; });
  var df = {};
  docs.forEach(function (d) { for (var k in d.g) df[k] = (df[k] || 0) + 1; });
  var N = docs.length, idf = {};
  for (var k in df) idf[k] = Math.log((N + 1) / (df[k] + 1)) + 1;
  function vec(g) {
    var v = {}, n = 0;
    for (var k in g) { if (!idf[k]) continue; v[k] = (1 + Math.log(g[k])) * idf[k]; n += v[k] * v[k]; }
    n = Math.sqrt(n) || 1;
    for (var k2 in v) v[k2] /= n;
    return v;
  }
  docs.forEach(function (d) { d.v = vec(d.g); });
  return {
    size: N,
    predict: function (text) {
      var q = vec(botGrams(text)), best = {};
      docs.forEach(function (d) {
        var s = 0;
        for (var k in q) if (d.v[k]) s += q[k] * d.v[k];
        if (!best[d.intent] || s > best[d.intent]) best[d.intent] = s;
      });
      var ranked = Object.keys(best).map(function (i) { return { intent: i, sim: best[i] }; }).sort(function (a, b) { return b.sim - a.sim; });
      var top = ranked[0] || { intent: '', sim: 0 };
      // ความมั่นใจ = ความคล้ายกับตัวอย่างที่ใกล้ที่สุด × ระยะห่างจากประเภทอันดับสอง
      var gap = ranked[1] ? top.sim - ranked[1].sim : top.sim;
      var conf = Math.max(0, Math.min(1, top.sim * 1.25)) * Math.min(1, 0.55 + gap * 3);
      return { intent: top.intent, conf: Math.round(conf * 100) / 100, sim: top.sim, ranked: ranked.slice(0, 3) };
    },
  };
}
